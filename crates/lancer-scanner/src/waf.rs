#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WafDetection {
    pub name: String,
    pub bypass_notes: Vec<String>,
    pub matched_signals: Vec<String>,
}

pub fn detect(response: &HttpResponse) -> Vec<WafDetection> {
    let body = response.body_text().unwrap_or("");
    let mut hits = Vec::new();
    for sig in SIGNATURES {
        let mut signals = Vec::new();
        for (h, expected) in sig.headers {
            if let Some(v) = response.header(h) {
                let v_lower = v.to_ascii_lowercase();
                if expected.is_empty() || v_lower.contains(&expected.to_ascii_lowercase()) {
                    signals.push(format!("header `{h}` = `{v}`"));
                }
            }
        }
        if !sig.cookies.is_empty() {
            for h in &response.headers {
                if h.name.eq_ignore_ascii_case("Set-Cookie") {
                    for c in sig.cookies {
                        if h.value.starts_with(c) {
                            signals.push(format!("cookie `{c}*` present"));
                        }
                    }
                }
            }
        }
        for s in sig.body_contains {
            if !s.is_empty() && body.contains(s) {
                signals.push(format!("body contains `{s}`"));
            }
        }
        if !signals.is_empty() {
            hits.push(WafDetection {
                name: sig.name.to_string(),
                bypass_notes: sig.bypass_notes.iter().map(|s| s.to_string()).collect(),
                matched_signals: signals,
            });
        }
    }
    hits
}
